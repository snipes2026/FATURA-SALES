import type { Metadata } from "next";
import { eq } from "drizzle-orm";
import { notFound } from "next/navigation";
import { LedgerTable } from "@/app/(app)/customers/_components/ledger-table";
import { readLedgerParams } from "@/app/(app)/customers/_lib/params";
import { PrintToolbar } from "@/components/print-toolbar";
import { db, schema } from "@/db";
import { formatDate, formatDateTime } from "@/lib/dates";
import { stateName } from "@/lib/india";
import { customerLedger } from "@/lib/sales/ledger";
import { requirePermission } from "@/lib/session";

export const metadata: Metadata = { title: "Customer Ledger" };

/** A4 customer ledger — print, or "Save as PDF" from the print dialog. */
export default async function CustomerLedgerPrint({ searchParams }: { searchParams: Promise<{ customer?: string; from?: string; to?: string; auto?: string }> }) {
  await requirePermission("sales.view");
  const sp = await searchParams;
  const { customer, from, to } = await readLedgerParams(sp);
  if (!customer) notFound();
  const [ledger, [company]] = await Promise.all([customerLedger(db, customer.id, from, to), db.select().from(schema.companyProfile).where(eq(schema.companyProfile.id, 1))]);

  return (
    <>
      <style>{`
        @page { size: A4 portrait; margin: 10mm; }
        @media print { .no-print { display: none !important; } .page { box-shadow: none !important; margin: 0 !important; padding: 0 !important; width: auto !important; } }
        .page { font-family: Arial, Helvetica, sans-serif; font-size: 9pt; color: #000; }
        thead { display: table-header-group; }
        tr { break-inside: avoid; }
      `}</style>
      <PrintToolbar title={`Ledger ${customer.name} · Fatura Desk`} label={customer.name} subtitle="A4 · Customer Ledger" autoPrint={sp.auto === "1"} />
      <div className="page mx-auto my-4 w-[210mm] bg-white p-[10mm] shadow-lg">
        <div className="flex items-start justify-between border-b-2 border-black pb-2">
          <div>
            <p className="text-[13pt] font-bold uppercase">{company?.name}</p>
            {company?.address && <p className="whitespace-pre-line">{company.address}</p>}
            {company?.gstin && <p>GSTIN: {company.gstin}</p>}
          </div>
          <div className="text-right">
            <p className="text-[12pt] font-bold">CUSTOMER LEDGER</p>
            <p>
              {formatDate(from)} to {formatDate(to)}
            </p>
          </div>
        </div>
        <div className="my-2">
          <p className="font-bold">{customer.name}</p>
          <p>{[customer.address, customer.phone, customer.gstin ? `GSTIN ${customer.gstin}` : null, stateName(customer.stateCode)].filter(Boolean).join(" · ")}</p>
        </div>
        <LedgerTable ledger={ledger} from={from} to={to} print />
        <p className="mt-4 border-t border-black/30 pt-1 text-right text-[7pt] text-black/60">Generated by Fatura Desk · {formatDateTime(new Date())}</p>
      </div>
    </>
  );
}
